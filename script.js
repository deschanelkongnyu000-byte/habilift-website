/* ==========================================================================
   THEME MANAGER (Light / Dark Mode with Persistence)
   ========================================================================== */
function getPreferredTheme() {
  const saved = localStorage.getItem("habilift_theme");
  if (saved) return saved;
  return window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
}

function applyTheme(theme, persist = true) {
  document.documentElement.setAttribute("data-theme", theme);
  if (persist) localStorage.setItem("habilift_theme", theme);

  const siteLogo = document.querySelector("#site-logo");
  if (siteLogo) {
    siteLogo.src = theme === "dark" ? "logo-light.png" : "logo.png";
  }

  const themeToggle = document.querySelector("#theme-toggle");
  if (themeToggle) {
    themeToggle.setAttribute("aria-label", theme === "dark" ? "Switch to light theme" : "Switch to dark theme");
    themeToggle.setAttribute("aria-pressed", theme === "dark" ? "true" : "false");
  }
}

function toggleTheme() {
  const current = document.documentElement.getAttribute("data-theme") === "dark" ? "dark" : "light";
  const target = current === "dark" ? "light" : "dark";
  applyTheme(target, true);
}

// Initial theme application
applyTheme(getPreferredTheme(), false);

const themeToggleBtn = document.querySelector("#theme-toggle");
if (themeToggleBtn) {
  themeToggleBtn.addEventListener("click", toggleTheme);
}

/* ==========================================================================
   LANGUAGE / i18n MANAGER (English & French with Persistence)
   ========================================================================== */
let currentLang = localStorage.getItem("habilift_lang") || "en";

function updateHeroCaption(slide) {
  if (!slide || !captionLine || !captionEm) return;
  if (currentLang === "fr") {
    captionLine.textContent = slide.dataset.captionFr || slide.dataset.caption;
    captionEm.textContent = slide.dataset.captionEmFr || slide.dataset.captionEm;
  } else {
    captionLine.textContent = slide.dataset.caption;
    captionEm.textContent = slide.dataset.captionEm;
  }
}

function setLanguage(lang, persist = true) {
  currentLang = lang;
  if (persist) localStorage.setItem("habilift_lang", lang);
  document.documentElement.setAttribute("lang", lang);

  // Update dynamic page title if on placeholder
  const pageParam = new URLSearchParams(window.location.search).get("page");
  if (pageParam && pageTitles[lang] && pageTitles[lang][pageParam]) {
    const title = pageTitles[lang][pageParam];
    document.title = `${title} — HabiLift`;
    const placeholder = document.querySelector("#placeholder");
    if (placeholder && !placeholder.hidden) {
      placeholder.innerHTML = `<p class="eyebrow"><span class="eyebrow-dot"></span> ${lang === "fr" ? "La suite de l’histoire HabiLift" : "The next part of the HabiLift story"}</p><h1>${title}.</h1><p>${lang === "fr" ? "Cette page fait partie de la structure du site HabiLift et est prête pour son contenu dédié." : "This page is part of the HabiLift website structure and is ready for its own content."}</p><a class="button button-primary" href="index.html">${lang === "fr" ? "Retour à l'accueil" : "Back to homepage"} <span aria-hidden="true">↗</span></a>`;
    }
  }

  // Update all elements with data-i18n
  const dict = i18n[lang] || i18n.en;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  // Update placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach(input => {
    const key = input.getAttribute("data-i18n-placeholder");
    if (dict[key]) {
      input.setAttribute("placeholder", dict[key]);
    }
  });

  // Update language selector buttons
  document.querySelectorAll(".lang-btn").forEach(btn => {
    const isActive = btn.dataset.lang === lang;
    btn.classList.toggle("is-active", isActive);
    btn.setAttribute("aria-pressed", String(isActive));
  });

  // Update hero slide caption
  const currentSlide = heroSlides[activeSlide] || heroSlides[0];
  if (currentSlide) {
    updateHeroCaption(currentSlide);
  }

  // Update modal if currently open
  if (storyModal && storyModal.classList.contains("is-open") && activeModalStoryId) {
    renderModalStory(activeModalStoryId);
  }
}

document.querySelectorAll(".lang-btn").forEach(btn => {
  btn.addEventListener("click", () => {
    const targetLang = btn.dataset.lang;
    if (targetLang && targetLang !== currentLang) {
      setLanguage(targetLang, true);
    }
  });
});

