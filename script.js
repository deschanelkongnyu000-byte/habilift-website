const heroSlides = [...document.querySelectorAll(".hero-slide")];
const carouselDots = [...document.querySelectorAll(".carousel-dot")];
const captionLine = document.querySelector(".caption-line");
const captionEm = document.querySelector(".caption-em");
let activeSlide = 0;
let carouselTimer;

function showHeroSlide(index) {
  if (!heroSlides.length) return;
  const nextIndex = (index + heroSlides.length) % heroSlides.length;
  const previous = heroSlides[activeSlide];
  const next = heroSlides[nextIndex];
  if (nextIndex === activeSlide) return;

  carouselDots.forEach((dot, dotIndex) => {
    const isActive = dotIndex === nextIndex;
    dot.classList.toggle("is-active", isActive);
    dot.setAttribute("aria-pressed", String(isActive));
  });

  const updateCaption = () => updateHeroCaption(next);

  if (!reducedMotion && window.gsap) {
    gsap.set(previous, { zIndex: 2 });
    gsap.set(next, { zIndex: 3 });
    gsap.set(next, { autoAlpha: 1, scale: 1.08, clipPath: "inset(0 0 0 100%)" });
    const transition = gsap.timeline({ onStart: updateCaption, onComplete: () => gsap.set(previous, { autoAlpha: 0, zIndex: 1, clipPath: "inset(0 0 0 0%)" }) });
    transition.to(previous, { scale: 1.04, duration: 1, ease: "power2.inOut" }, 0)
      .to(next, { scale: 1, clipPath: "inset(0 0 0 0%)", duration: 1, ease: "power3.inOut" }, 0)
      .fromTo(".visual-caption", { y: 9, opacity: 0 }, { y: 0, opacity: 1, duration: 0.5, ease: "power2.out" }, 0.15);
  } else {
    previous.classList.remove("is-active");
    next.classList.add("is-active");
    updateCaption();
  }
  activeSlide = nextIndex;
}

function startCarousel() {
  clearInterval(carouselTimer);
  if (!reducedMotion) carouselTimer = window.setInterval(() => showHeroSlide(activeSlide + 1), 3200);
}

carouselDots.forEach((dot, index) => dot.addEventListener("click", () => {
  showHeroSlide(index);
}));

const heroVisual = document.querySelector(".hero-visual");
if (heroVisual) {
  heroVisual.addEventListener("pointerenter", () => clearInterval(carouselTimer));
  heroVisual.addEventListener("pointerleave", startCarousel);
  heroVisual.addEventListener("focusin", () => clearInterval(carouselTimer));
  heroVisual.addEventListener("focusout", (event) => {
    if (!heroVisual.contains(event.relatedTarget)) startCarousel();
  });
}
document.addEventListener("visibilitychange", () => {
  if (document.hidden) clearInterval(carouselTimer);
  else startCarousel();
});
startCarousel();

/* ==========================================================================
   HERO 3D MOUSE PARALLAX CONTROLLER
   ========================================================================== */
const heroSection = document.querySelector(".hero");
const heroPhoto = document.querySelector(".hero-photo");
const heroShapeBackdrop = document.querySelector(".hero-shape-backdrop");
const visualLabel = document.querySelector(".visual-label");
const visualCaption = document.querySelector(".visual-caption");
const heroSpotlight = document.querySelector(".hero-spotlight");

if (heroSection && heroPhoto && !reducedMotion) {
  let mouseX = 0, mouseY = 0;
  let targetPixelX = 0, targetPixelY = 0;
  let currentPixelX = 0, currentPixelY = 0;
  let currentX = 0, currentY = 0;
  let isHovering = false;

  const updatePointer = (clientX, clientY) => {
    const rect = heroSection.getBoundingClientRect();
    targetPixelX = clientX - rect.left;
    targetPixelY = clientY - rect.top;

    if (!isHovering && currentPixelX === 0) {
      currentPixelX = targetPixelX;
      currentPixelY = targetPixelY;
    }

    mouseX = (targetPixelX / rect.width - 0.5) * 2;
    mouseY = (targetPixelY / rect.height - 0.5) * 2;
    isHovering = true;
  };

  heroSection.addEventListener("mousemove", (e) => updatePointer(e.clientX, e.clientY));
  heroSection.addEventListener("pointermove", (e) => updatePointer(e.clientX, e.clientY));

  heroSection.addEventListener("mouseleave", () => {
    mouseX = 0;
    mouseY = 0;
    isHovering = false;
    
    if (window.gsap) {
      gsap.to(heroPhoto, { rotateY: 0, rotateX: 0, x: 0, y: 0, duration: 0.6, ease: "power2.out" });
      if (heroShapeBackdrop) gsap.to(heroShapeBackdrop, { rotateY: 0, rotateX: 0, x: 0, y: 0, duration: 0.6, ease: "power2.out" });
      if (visualLabel) gsap.to(visualLabel, { x: 0, y: 0, duration: 0.6, ease: "power2.out" });
      if (visualCaption) gsap.to(visualCaption, { x: 0, y: 0, rotation: 5, duration: 0.6, ease: "power2.out" });
    } else {
      heroPhoto.style.transform = "rotateY(0deg) rotateX(0deg)";
      if (heroShapeBackdrop) heroShapeBackdrop.style.transform = "rotateY(0deg) rotateX(0deg)";
      if (visualLabel) visualLabel.style.transform = "translate(0, 0)";
      if (visualCaption) visualCaption.style.transform = "translate(0, 0) rotate(5deg)";
    }
  });

  function renderHeroParallax() {
    if (isHovering) {
      currentX += (mouseX - currentX) * 0.08;
      currentY += (mouseY - currentY) * 0.08;

      if (heroSpotlight) {
        currentPixelX += (targetPixelX - currentPixelX) * 0.12;
        currentPixelY += (targetPixelY - currentPixelY) * 0.12;
        heroSection.style.setProperty("--mouse-x", `${currentPixelX}px`);
        heroSection.style.setProperty("--mouse-y", `${currentPixelY}px`);
      }

      const tiltY = currentX * 5.0;
      const tiltX = -currentY * 5.0;
      const panX = currentX * 6.0;
      const panY = currentY * 6.0;

      heroPhoto.style.transform = `perspective(1100px) rotateY(${tiltY}deg) rotateX(${tiltX}deg) translate3d(${panX}px, ${panY}px, 0px)`;

      if (heroShapeBackdrop) {
        heroShapeBackdrop.style.transform = `perspective(1100px) rotateY(${tiltY}deg) rotateX(${tiltX}deg) translate3d(${panX * 0.75}px, ${panY * 0.75}px, 0px)`;
      }

      if (visualLabel) {
        visualLabel.style.transform = `translate3d(${-currentX * 6}px, ${-currentY * 6}px, 0px)`;
      }
      if (visualCaption) {
        visualCaption.style.transform = `translate3d(${currentX * 5}px, ${currentY * 5}px, 0px) rotate(${5 + currentX * 1.5}deg)`;
      }
    }
    requestAnimationFrame(renderHeroParallax);
  }
  requestAnimationFrame(renderHeroParallax);
}

