// Gentle Ambient Audio Voice-Note Simulation using Web Audio API
let activeAudioCtx = null;
let activePlayingBtn = null;
let activeOscillators = [];

function stopVoiceNote() {
  if (activeOscillators.length) {
    activeOscillators.forEach(osc => {
      try { osc.stop(); osc.disconnect(); } catch (e) {}
    });
    activeOscillators = [];
  }
  if (activePlayingBtn) {
    activePlayingBtn.classList.remove("is-playing");
    activePlayingBtn = null;
  }
}

function playCalmingVoiceNote(button) {
  stopVoiceNote();

  try {
    const AudioContext = window.AudioContext || window.webkitAudioContext;
    if (!AudioContext) return;
    
    if (!activeAudioCtx) activeAudioCtx = new AudioContext();
    if (activeAudioCtx.state === "suspended") activeAudioCtx.resume();

    button.classList.add("is-playing");
    activePlayingBtn = button;

    const frequencies = [349.23, 440.0, 523.25, 659.25];
    const now = activeAudioCtx.currentTime;

    frequencies.forEach((freq, idx) => {
      const osc = activeAudioCtx.createOscillator();
      const gain = activeAudioCtx.createGain();

      osc.type = "sine";
      osc.frequency.setValueAtTime(freq, now + idx * 0.25);
      
      gain.gain.setValueAtTime(0, now);
      gain.gain.linearRampToValueAtTime(0.045 / frequencies.length, now + 0.4 + idx * 0.2);
      gain.gain.exponentialRampToValueAtTime(0.0001, now + 4.5);

      osc.connect(gain);
      gain.connect(activeAudioCtx.destination);

      osc.start(now + idx * 0.15);
      osc.stop(now + 4.8);
      activeOscillators.push(osc);
    });

    setTimeout(() => {
      if (activePlayingBtn === button) {
        button.classList.remove("is-playing");
        activePlayingBtn = null;
      }
    }, 4800);

  } catch (err) {
    console.warn("Audio playback not supported or user gesture required", err);
  }
}

document.querySelectorAll(".voice-note-btn").forEach(btn => {
  btn.addEventListener("click", () => {
    if (btn.classList.contains("is-playing")) {
      stopVoiceNote();
    } else {
      playCalmingVoiceNote(btn);
    }
  });
});

